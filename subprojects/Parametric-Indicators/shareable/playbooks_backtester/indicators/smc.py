"""Group C — ICT / Smart-Money-Concept structure detectors (causal, no look-ahead).

These are the OHLC-derived structures generated by the two-phase pipeline (decision #11). FVG uses
wick geometry; structure/golf use closes/bodies per the frozen spec. Order-block/breaker (a stateful
machine over structure) builds on market_structure and lands in a later increment.

STUBS first (TDD: tests/test_smc.py).

PERFORMANCE (2026-07-11): `breaker_blocks` is a stateful per-bar scan over the 1-MINUTE frame (~1M bars),
and profiling made it the single hottest function in an optimizer campaign — 0.76 s PER CALL, ~27% of a
trial's compute once the trial store is taken out. It is Numba-JITted below. The JIT is a pure
accelerator: `_breaker_blocks_py` remains the reference implementation and `tests/test_smc_numba_parity.py`
asserts the two agree bit-for-bit on real data across every swing_l. If Numba is missing, the pure-Python
path is used automatically, so this is a speed-only change with no behavioural surface.
"""
from __future__ import annotations

import numpy as np

try:                                    # optional accelerator — absent ⇒ pure-Python reference path
    from numba import njit
    _HAVE_NUMBA = True
except ImportError:                     # pragma: no cover
    _HAVE_NUMBA = False

    def njit(*a, **k):                  # no-op decorator so the module still imports
        def deco(f):
            return f
        return deco if not a else a[0]


def fvg(high: np.ndarray, low: np.ndarray):
    """3-candle Fair Value Gap (wick-based). At bar t (the 3rd candle):
      bullish iff low[t] > high[t-2]  → zone [high[t-2], low[t]]
      bearish iff high[t] < low[t-2]  → zone [high[t],   low[t-2]]
    Returns (bull, bear, zone_lo, zone_hi): bull/bear bool arrays; zone_lo/hi float (NaN if none)."""
    h = np.asarray(high, float); l = np.asarray(low, float)
    n = len(h)
    bull = np.zeros(n, bool); bear = np.zeros(n, bool)
    zlo = np.full(n, np.nan); zhi = np.full(n, np.nan)
    for t in range(2, n):
        if l[t] > h[t - 2]:
            bull[t] = True; zlo[t] = h[t - 2]; zhi[t] = l[t]
        elif h[t] < l[t - 2]:
            bear[t] = True; zlo[t] = h[t]; zhi[t] = l[t - 2]
    return bull, bear, zlo, zhi


def market_structure(close: np.ndarray, swing_l: int = 2):
    """Close-based fractal swings. swing_high[t]=True iff close[t] strictly exceeds the swing_l
    closes on BOTH sides; mirror for swing_low. (Pivot index marked; confirmation timing is the
    consumer's job — a pivot is only knowable swing_l bars later.) Returns (swing_high, swing_low)."""
    c = np.asarray(close, float)
    n = len(c)
    sh = np.zeros(n, bool); sl = np.zeros(n, bool)
    L = int(swing_l)
    if L < 1 or n <= 2 * L:
        return sh, sl
    # Vectorised fractal (task #210): sh[t] ⇔ c[t] strictly above each of the L closes on BOTH sides.
    # ANDing the per-offset comparisons is identical to the original per-window `.all()` (proven
    # bit-identical vs the python loop on real 1-min closes) but runs L array-ops instead of n×L scalars.
    gt_l = np.ones(n, bool); gt_r = np.ones(n, bool)
    lt_l = np.ones(n, bool); lt_r = np.ones(n, bool)
    for k in range(1, L + 1):
        gt_l[k:] &= c[k:] > c[:-k]      # c[t] > c[t-k]
        lt_l[k:] &= c[k:] < c[:-k]
        gt_r[:-k] &= c[:-k] > c[k:]     # c[t] > c[t+k]
        lt_r[:-k] &= c[:-k] < c[k:]
    sh = gt_l & gt_r; sl = lt_l & lt_r
    sh[:L] = False; sh[n - L:] = False   # pivot only defined for t ∈ [L, n-L)
    sl[:L] = False; sl[n - L:] = False
    return sh, sl


def fvg_active_direction(high: np.ndarray, low: np.ndarray, lookback: int = 3) -> np.ndarray:
    """Per-bar directional bias from the most recent FVG within `lookback` bars: +1 if the latest
    FVG (within lookback) is bullish, -1 bearish, 0 if none recent. The retrace-into-zone entry is
    handled by the indicator's retrace param + the engine resolver; this is the directional read."""
    bull, bear, _, _ = fvg(high, low)
    n = len(bull)
    out = np.zeros(n, dtype=np.int8)
    last_dir = 0
    last_idx = -10 ** 9
    for t in range(n):
        if bull[t]:
            last_dir, last_idx = 1, t
        elif bear[t]:
            last_dir, last_idx = -1, t
        if last_dir != 0 and (t - last_idx) <= lookback:
            out[t] = last_dir
    return out


def structure_trend(close: np.ndarray, swing_l: int = 2) -> np.ndarray:
    """Per-bar trend stance from confirmed swing structure (causal). A swing pivot at index p is
    only known swing_l bars later. stance[t] = +1 when the latest two confirmed swing highs are
    rising AND the latest two confirmed swing lows are rising (HH+HL uptrend); -1 for LH+LL; the
    stance is carried forward between structure updates; 0 until enough swings exist."""
    c = np.asarray(close, float)
    n = len(c)
    sh, sl = market_structure(c, swing_l)
    L = int(swing_l)
    out = np.zeros(n, dtype=np.int8)
    highs, lows = [], []
    cur = 0
    for t in range(n):
        p = t - L
        if p >= 0:
            if sh[p]:
                highs.append(c[p])
            if sl[p]:
                lows.append(c[p])
        if len(highs) >= 2 and len(lows) >= 2:
            hh, hl = highs[-1] > highs[-2], lows[-1] > lows[-2]
            lh, ll = highs[-1] < highs[-2], lows[-1] < lows[-2]
            if hh and hl:
                cur = 1
            elif lh and ll:
                cur = -1
            # else: carry the prior stance
        out[t] = cur
    return out


def order_blocks(open_, high, low, close, swing_l: int = 2, signal_at=None):
    """Causal order-block detection. A bullish OB = the last down-close candle before a close that
    breaks ABOVE the most recent confirmed swing high; bearish OB = last up-close candle before a
    close breaking BELOW the most recent confirmed swing low. Once price CLOSES beyond an OB it
    converts to a breaker (role flips) and is no longer usable as an OB.

    Returns ob_signal: per-bar int8 ∈ {+1,-1,0} — +1 while price trades within a live BULLISH OB
    zone (a long-reaction zone), -1 within a live BEARISH OB zone, else 0.

    signal_at (task #210, Step E): an optional array of bar indices whose output value will actually be
    READ (the decision bars' sampled 1-minute candles). When given, the per-bar OVERLAP signal is
    computed ONLY at those indices (the zone STATE — swings, breaks, pruning — still advances every bar,
    so the value at each requested index is identical to the full computation); other bars stay 0 and
    are never read. signal_at=None ⇒ compute every bar (the original behaviour, used by the decision-TF
    path + parity tests). Frozen reference: indicators/_reference.order_blocks_ref.
    """
    o = np.asarray(open_, float); h = np.asarray(high, float)
    l = np.asarray(low, float); c = np.asarray(close, float)
    n = len(c)
    sh, sl = market_structure(c, swing_l)
    L = int(swing_l)
    out = np.zeros(n, dtype=np.int8)
    want = None
    if signal_at is not None:
        want = np.zeros(n, dtype=bool)
        idx = np.asarray(signal_at, dtype=np.intp)
        want[idx[(idx >= 0) & (idx < n)]] = True
    swh = swl = None
    last_down = last_up = None
    # Live zones as numpy arrays (lo, hi) instead of Python lists (task #210, Step C′). Appends (on
    # breaks) are rare; the per-bar overlap (np.any) and pruning (boolean mask) are VECTORISED — exactly
    # the same operations as the list version, at C speed. Output is unchanged (proven bit-identical vs
    # _reference.order_blocks_ref). signal_at gating (Step E) is preserved.
    bull_lo = np.empty(0, dtype=float); bull_hi = np.empty(0, dtype=float)
    bear_lo = np.empty(0, dtype=float); bear_hi = np.empty(0, dtype=float)
    prev_above = prev_below = False
    for t in range(n):
        p = t - L
        if p >= 0:
            if sh[p]:
                swh = c[p]
            if sl[p]:
                swl = c[p]
        # fresh break above the latest swing high → bullish OB at the last down-close candle
        if swh is not None:
            above = c[t] > swh
            if above and not prev_above and last_down is not None:
                lo = min(o[last_down], c[last_down]); hi = max(o[last_down], c[last_down])
                bull_lo = np.append(bull_lo, lo); bull_hi = np.append(bull_hi, hi)
            prev_above = above
        if swl is not None:
            below = c[t] < swl
            if below and not prev_below and last_up is not None:
                lo = min(o[last_up], c[last_up]); hi = max(o[last_up], c[last_up])
                bear_lo = np.append(bear_lo, lo); bear_hi = np.append(bear_hi, hi)
            prev_below = below
        # per-bar reaction signal: overlap with a live zone (bull preferred). Skipped where the value is
        # never read (want[t] False) — out[t] stays 0; the state updates below STILL run every bar.
        if want is None or want[t]:
            s = 0
            if bull_lo.size and np.any((l[t] <= bull_hi) & (h[t] >= bull_lo)):
                s = 1
            elif bear_lo.size and np.any((l[t] <= bear_hi) & (h[t] >= bear_lo)):
                s = -1
            out[t] = s
        # conversion to breaker (burned into): bull OB dies on a close BELOW it (keep lo ≤ c[t]); bear on
        # a close ABOVE it (keep hi ≥ c[t]). Realloc only when something actually drops out.
        if bull_lo.size:
            keep = bull_lo <= c[t]
            if not keep.all():
                bull_lo = bull_lo[keep]; bull_hi = bull_hi[keep]
        if bear_lo.size:
            keep = bear_hi >= c[t]
            if not keep.all():
                bear_lo = bear_lo[keep]; bear_hi = bear_hi[keep]
        # track last opposite-close candle AFTER using prior state
        if c[t] < o[t]:
            last_down = t
        elif c[t] > o[t]:
            last_up = t
    return out


def swing_labels(close: np.ndarray, swing_l: int = 2):
    """Label every confirmed close-based swing pivot as HH / LH (highs) or HL / LL (lows).

    Built on `market_structure` (a pivot at index p is only knowable swing_l bars later). Each swing HIGH
    is compared to the PRIOR swing high → 'HH' if higher else 'LH'; each swing LOW to the prior swing low →
    'HL' if higher else 'LL'. The first high/low has no prior → '' (the study marks it FIRST). Causal: the
    comparison at pivot p uses only earlier pivots.

    Returns (kind, label, confirmed_at):
      kind        int8  +1 at a swing-high bar, -1 at a swing-low bar, 0 otherwise
      label       object  'HH'|'LH'|'HL'|'LL'|'' (non-empty only at pivot bars)
      confirmed_at int   p + swing_l (the bar at which the pivot becomes knowable), -1 off-pivot
    """
    c = np.asarray(close, float)
    n = len(c)
    sh, sl = market_structure(c, swing_l)
    L = int(swing_l)
    kind = np.zeros(n, np.int8)
    label = np.full(n, "", dtype=object)
    confirmed_at = np.full(n, -1, dtype=int)
    last_high = last_low = None
    for p in range(n):                                   # pivots in chronological (index) order
        if sh[p]:
            kind[p] = 1
            label[p] = ("HH" if c[p] > last_high else "LH") if last_high is not None else ""
            last_high = c[p]; confirmed_at[p] = p + L
        elif sl[p]:
            kind[p] = -1
            label[p] = ("HL" if c[p] > last_low else "LL") if last_low is not None else ""
            last_low = c[p]; confirmed_at[p] = p + L
    return kind, label, confirmed_at


def ifvg(high: np.ndarray, low: np.ndarray, close: np.ndarray, signal_at=None) -> np.ndarray:
    """Inverse Fair Value Gap (causal). An FVG that price CLOSES through inverts and becomes an opposing
    S/R zone (the 'burned-into' flip):
      • bullish FVG [zlo,zhi] (support) → bearish IFVG (resistance) once a close < zlo;
      • bearish FVG [zlo,zhi] (resistance) → bullish IFVG (support) once a close > zhi.
    Per-bar signal int8: +1 while the current bar overlaps a live BULLISH IFVG (support), -1 a live BEARISH
    IFVG (resistance), else 0. A live IFVG dies when price closes back through it (bull IFVG: close < zlo;
    bear IFVG: close > zhi). Trigger = a CLOSE (locked decision A4). signal_at as in `order_blocks`."""
    h = np.asarray(high, float); l = np.asarray(low, float); c = np.asarray(close, float)
    n = len(c)
    out = np.zeros(n, np.int8)
    want = None
    if signal_at is not None:
        want = np.zeros(n, bool); idx = np.asarray(signal_at, dtype=np.intp)
        want[idx[(idx >= 0) & (idx < n)]] = True
    fvgs = []                                            # live, un-inverted FVGs: [zlo, zhi, dir]
    ifvgs = []                                           # live inverse zones: [zlo, zhi, dir(flipped)]
    for t in range(n):
        # 1) form a new FVG at the 3rd candle (uses t, t-2 only)
        if t >= 2:
            if l[t] > h[t - 2]:
                fvgs.append([h[t - 2], l[t], 1])
            elif h[t] < l[t - 2]:
                fvgs.append([h[t], l[t - 2], -1])
        # 2) invert FVGs that this close burned through; drop them from the live-FVG list
        keep = []
        for zlo, zhi, d in fvgs:
            if d == 1 and c[t] < zlo:
                ifvgs.append([zlo, zhi, -1])             # bullish FVG failed → bearish IFVG
            elif d == -1 and c[t] > zhi:
                ifvgs.append([zlo, zhi, 1])              # bearish FVG failed → bullish IFVG
            else:
                keep.append([zlo, zhi, d])
        fvgs = keep
        # 3) per-bar signal from live IFVGs (overlap with current bar); bull preferred
        if want is None or want[t]:
            s = 0
            for zlo, zhi, d in ifvgs:
                if l[t] <= zhi and h[t] >= zlo:
                    s = d;
                    if d == 1:
                        break
            out[t] = s
        # 4) IFVG death: price closes back through it
        ifvgs = [[zlo, zhi, d] for zlo, zhi, d in ifvgs
                 if not ((d == 1 and c[t] < zlo) or (d == -1 and c[t] > zhi))]
    return out


@njit(cache=True, nogil=True)
def _breaker_kernel(o, h, l, c, sh, sl, L, want, use_want):
    """Numba twin of `_breaker_blocks_py`'s scan. The Python lists become preallocated arrays with a live
    count, compacted IN ORDER — insertion order is load-bearing: the per-bar signal scans breakers oldest
    first, a bullish overlap short-circuits (+1 wins), otherwise the LAST overlapping bearish one stands.

    Capacities: at most one bull-OB and one bear-OB are born per bar ⇒ each OB list ≤ n, and every breaker
    comes from retiring an OB ⇒ cumulative breaker appends ≤ 2n."""
    n = c.shape[0]
    out = np.zeros(n, np.int8)

    bull_lo = np.empty(n + 1, np.float64); bull_hi = np.empty(n + 1, np.float64); n_bull = 0
    bear_lo = np.empty(n + 1, np.float64); bear_hi = np.empty(n + 1, np.float64); n_bear = 0
    brk_lo = np.empty(2 * n + 2, np.float64)
    brk_hi = np.empty(2 * n + 2, np.float64)
    brk_d = np.empty(2 * n + 2, np.int8); n_brk = 0

    swh = 0.0; has_swh = False
    swl = 0.0; has_swl = False
    last_down = -1; last_up = -1
    prev_above = False; prev_below = False

    for t in range(n):
        p = t - L
        if p >= 0:
            if sh[p]:
                swh = c[p]; has_swh = True
            if sl[p]:
                swl = c[p]; has_swl = True

        if has_swh:
            above = c[t] > swh
            if above and (not prev_above) and last_down >= 0:
                a = o[last_down]; b = c[last_down]
                bull_lo[n_bull] = a if a < b else b
                bull_hi[n_bull] = a if a > b else b
                n_bull += 1
            prev_above = above

        if has_swl:
            below = c[t] < swl
            if below and (not prev_below) and last_up >= 0:
                a = o[last_up]; b = c[last_up]
                bear_lo[n_bear] = a if a < b else b
                bear_hi[n_bear] = a if a > b else b
                n_bear += 1
            prev_below = below

        # OB → breaker conversion on a close beyond the OB (role + direction flip); stable compaction
        k = 0
        for i in range(n_bull):
            if c[t] < bull_lo[i]:
                brk_lo[n_brk] = bull_lo[i]; brk_hi[n_brk] = bull_hi[i]; brk_d[n_brk] = -1; n_brk += 1
            else:
                bull_lo[k] = bull_lo[i]; bull_hi[k] = bull_hi[i]; k += 1
        n_bull = k

        k = 0
        for i in range(n_bear):
            if c[t] > bear_hi[i]:
                brk_lo[n_brk] = bear_lo[i]; brk_hi[n_brk] = bear_hi[i]; brk_d[n_brk] = 1; n_brk += 1
            else:
                bear_lo[k] = bear_lo[i]; bear_hi[k] = bear_hi[i]; k += 1
        n_bear = k

        # per-bar breaker reaction signal (overlap), bull preferred
        if (not use_want) or want[t]:
            s = np.int8(0)
            for i in range(n_brk):
                if l[t] <= brk_hi[i] and h[t] >= brk_lo[i]:
                    s = brk_d[i]
                    if brk_d[i] == 1:
                        break
            out[t] = s

        # breaker death: price closes back through it
        k = 0
        for i in range(n_brk):
            d = brk_d[i]
            dead = (d == 1 and c[t] < brk_lo[i]) or (d == -1 and c[t] > brk_hi[i])
            if not dead:
                brk_lo[k] = brk_lo[i]; brk_hi[k] = brk_hi[i]; brk_d[k] = d; k += 1
        n_brk = k

        if c[t] < o[t]:
            last_down = t
        elif c[t] > o[t]:
            last_up = t
    return out


def breaker_blocks(open_, high, low, close, swing_l: int = 2, signal_at=None) -> np.ndarray:
    """Tradeable BREAKER blocks (causal). See `_breaker_blocks_py` for the full spec — this dispatches to
    the Numba kernel when available (bit-identical; locked by tests/test_smc_numba_parity.py) and falls
    back to the pure-Python reference otherwise."""
    if not _HAVE_NUMBA:
        return _breaker_blocks_py(open_, high, low, close, swing_l, signal_at)
    o = np.ascontiguousarray(open_, dtype=np.float64)
    h = np.ascontiguousarray(high, dtype=np.float64)
    l = np.ascontiguousarray(low, dtype=np.float64)
    c = np.ascontiguousarray(close, dtype=np.float64)
    n = len(c)
    sh, sl = market_structure(c, swing_l)
    use_want = signal_at is not None
    if use_want:
        want = np.zeros(n, bool)
        idx = np.asarray(signal_at, dtype=np.intp)
        want[idx[(idx >= 0) & (idx < n)]] = True
    else:
        want = np.zeros(1, bool)          # unused; numba needs a concrete array
    return _breaker_kernel(o, h, l, c, np.ascontiguousarray(sh), np.ascontiguousarray(sl),
                           int(swing_l), want, use_want)


def _breaker_blocks_py(open_, high, low, close, swing_l: int = 2, signal_at=None) -> np.ndarray:
    """REFERENCE implementation (pure Python) — the semantics of record.

    Tradeable BREAKER blocks (causal). An order block that price CLOSES beyond is retired as an OB and
    flips role/colour into a breaker, then acts as an ENTRY zone in the FLIPPED direction (locked A9):
      • bullish OB (support) broken by a close BELOW it → BEARISH breaker (resistance / short zone);
      • bearish OB (resistance) broken by a close ABOVE it → BULLISH breaker (support / long zone).
    (Matches the user's colour-flip: top OB red→top breaker green is the bearish-OB→bullish-breaker case.)
    Per-bar signal int8: +1 within a live bullish breaker, -1 within a live bearish breaker, else 0. A
    breaker dies when price closes back through it. OB geometry = body (open,close), as in `order_blocks`."""
    o = np.asarray(open_, float); h = np.asarray(high, float)
    l = np.asarray(low, float); c = np.asarray(close, float)
    n = len(c)
    sh, sl = market_structure(c, swing_l)
    L = int(swing_l)
    out = np.zeros(n, np.int8)
    want = None
    if signal_at is not None:
        want = np.zeros(n, bool); idx = np.asarray(signal_at, dtype=np.intp)
        want[idx[(idx >= 0) & (idx < n)]] = True
    swh = swl = None
    last_down = last_up = None
    bull_ob = []                                         # live bullish OBs: [lo, hi]
    bear_ob = []                                         # live bearish OBs: [lo, hi]
    breakers = []                                        # live breakers: [lo, hi, dir]
    prev_above = prev_below = False
    for t in range(n):
        p = t - L
        if p >= 0:
            if sh[p]:
                swh = c[p]
            if sl[p]:
                swl = c[p]
        if swh is not None:
            above = c[t] > swh
            if above and not prev_above and last_down is not None:
                bull_ob.append([min(o[last_down], c[last_down]), max(o[last_down], c[last_down])])
            prev_above = above
        if swl is not None:
            below = c[t] < swl
            if below and not prev_below and last_up is not None:
                bear_ob.append([min(o[last_up], c[last_up]), max(o[last_up], c[last_up])])
            prev_below = below
        # OB → breaker conversion on a close beyond the OB (role + direction flip)
        keep_bull = []
        for lo, hi in bull_ob:
            if c[t] < lo:
                breakers.append([lo, hi, -1])            # bullish OB broken down → bearish breaker
            else:
                keep_bull.append([lo, hi])
        bull_ob = keep_bull
        keep_bear = []
        for lo, hi in bear_ob:
            if c[t] > hi:
                breakers.append([lo, hi, 1])             # bearish OB broken up → bullish breaker
            else:
                keep_bear.append([lo, hi])
        bear_ob = keep_bear
        # per-bar breaker reaction signal (overlap), bull preferred
        if want is None or want[t]:
            s = 0
            for lo, hi, d in breakers:
                if l[t] <= hi and h[t] >= lo:
                    s = d
                    if d == 1:
                        break
            out[t] = s
        # breaker death: price closes back through it
        breakers = [[lo, hi, d] for lo, hi, d in breakers
                    if not ((d == 1 and c[t] < lo) or (d == -1 and c[t] > hi))]
        if c[t] < o[t]:
            last_down = t
        elif c[t] > o[t]:
            last_up = t
    return out


def cisd(open_: np.ndarray, close: np.ndarray) -> np.ndarray:
    """CISD — Change In State of Delivery (STANDARD definition, locked A10). A 'delivery leg' is a run of
    consecutive same-colour candles; its reference level is the OPEN of the FIRST candle in the run. When a
    later candle CLOSES back through that open in the opposite direction, the state of delivery has changed:
      • bearish CISD (-1): a close BELOW the open of the most recent BULLISH (green) leg;
      • bullish CISD (+1): a close ABOVE the open of the most recent BEARISH (red) leg.
    Per-bar signal int8 ∈ {+1,-1,0}; fires on the bar that closes through. Causal (≤ t data only)."""
    o = np.asarray(open_, float); c = np.asarray(close, float)
    n = len(c)
    out = np.zeros(n, np.int8)
    bull_open = bear_open = None                          # open of the start of the latest green / red run
    prev_color = 0
    for t in range(n):
        color = 1 if c[t] > o[t] else (-1 if c[t] < o[t] else 0)
        if color == 1 and prev_color != 1:
            bull_open = o[t]                              # new green run starts here
        elif color == -1 and prev_color != -1:
            bear_open = o[t]                              # new red run starts here
        if bull_open is not None and c[t] < bull_open:
            out[t] = -1                                   # closed through the bullish leg's open → bearish
        elif bear_open is not None and c[t] > bear_open:
            out[t] = 1                                    # closed through the bearish leg's open → bullish
        if color != 0:
            prev_color = color
    return out


def golf_candle(open_: np.ndarray, high: np.ndarray, low: np.ndarray, close: np.ndarray,
                golf_n: int = 3) -> np.ndarray:
    """'Golf' = an N-candle ENGULFING reversal (WS-I review #2). For bar t (t ≥ N), returns
    +1 bullish / -1 bearish / 0 none, where N = golf_n:

      1. opposite colour to ALL N prior candles —
           bullish: current green (close>open) AND every prior t-N..t-1 is red (close<open);
           bearish: current red          AND every prior t-N..t-1 is green;
      2. range engulf (wicks): current.high ≥ max(high[t-N:t]) AND current.low ≤ min(low[t-N:t]);
      3. body filter: |close-open| ≥ 0.70 × prior_span, prior_span = max(high[t-N:t]) − min(low[t-N:t]).

    First N bars are 0. Dojis (close==open) are neither red nor green ⇒ break the colour test.
    """
    o = np.asarray(open_, float); h = np.asarray(high, float)
    lo = np.asarray(low, float); c = np.asarray(close, float)
    n = len(c)
    m = int(golf_n)
    out = np.zeros(n, np.int8)
    body = np.abs(c - o)
    for t in range(m, n):
        ph = h[t - m:t].max(); pl = lo[t - m:t].min(); span = ph - pl
        if not ((h[t] >= ph) and (lo[t] <= pl) and (body[t] >= 0.70 * span)):
            continue                                   # need wick-engulf + body ≥ 70% of prior span
        prior_red = bool(np.all(c[t - m:t] < o[t - m:t]))
        prior_green = bool(np.all(c[t - m:t] > o[t - m:t]))
        if c[t] > o[t] and prior_red:                  # bullish engulfing
            out[t] = 1
        elif c[t] < o[t] and prior_green:              # bearish engulfing
            out[t] = -1
    return out
